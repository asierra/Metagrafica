double text_width(TextState ts, string s) {
  if (ts.font_face==FN_COURIER)
    return s.length() * 600 * ts.font_size / 1000;

  // Un run FN_TEX_CMMI se DIBUJA partido: el griego (∈ cmmiUnicode) va en LM Math y
  // el no-griego (E, dígitos, =, espacio) en Times-Italic. Antes se MEDÍA todo con
  // cmmi_metrics_map, así que la medida no cuadraba con el render y el centrado/fit/
  // frac se iban a la deriva. Se mide cada byte con el mapa de la fuente REAL, con la
  // MISMA partición que los backends (plan_text_space.md, Parte A).
  if (ts.font_face == FN_TEX_CMMI) {
    const std::map<unsigned char, unsigned int> &gm = cmmiUnicode();
    double w = 0;
    for (unsigned char ch : s) {
      const FontMetricsMap &m = gm.count(ch) ? cmmi_metrics_map : serifitalic_metrics_map;
      auto it = m.find(ch);
      w += (it != m.end() ? it->second : 500) * ts.font_size / 1000;
    }
    return w;
  }

  double width = 0;
  FontMetricsMap fmmap;

  switch (ts.font_face) {
  default:
  case FN_SERIF:
    fmmap = serif_metrics_map;
    break;
  case FN_SERIF_BOLD:
    fmmap = serifbold_metrics_map;
    break;
  case FN_SERIF_ITALIC:
    fmmap = serifitalic_metrics_map;
    break;
  case FN_SYMBOL:
    fmmap = symbol_metrics_map;
    break;
  case FN_TEX_CMMI:
    fmmap = cmmi_metrics_map;
    break;
  case FN_SANSERIF:
    fmmap = sanserif_metrics_map;
    break;
  case FN_SANSERIF_ITALIC:
    fmmap = sanserifitalic_metrics_map;
    break;
  case FN_SANSERIF_ITALIC_BOLD:
  case FN_SANSERIF_BOLD:
    fmmap = sanserifbold_metrics_map;
    break;
  }
  for (auto &ch : s) {
    auto it = fmmap.find((unsigned char)ch);
    width += (it != fmmap.end() ? it->second : 500) * ts.font_size / 1000;   // find, no [ ]: sin 0 mudo
  }
  return width;
}

void Text::draw(Display &g) {
  // FN_NOFACE = "hereda la cara ambiente" (§7.3). Se resuelve contra la ambiente que
  // TextLine::draw guardó ANTES de la línea; solo si nadie la fijó nunca se cae al
  // comportamiento viejo (no llamar a setFontFace y dejar que los guards de
  // EPSDisplay/PDFDisplay pongan Times-Roman).
  //
  // ⚠️ El orden importa y es la mitad del bug que esto arregla: setRelFontSize
  // INVALIDA dspstate.fontFace (lo pone en FN_NOFACE) justo para forzar que la
  // siguiente llamada a setFontFace re-emita la fuente al tamaño nuevo. Si el trozo
  // se salta setFontFace, esa re-emisión NUNCA ocurre y el dispositivo se queda con
  // la fuente del trozo anterior: la cara Y el tamaño. Por eso la prosa que sigue a
  // un sub/superíndice salía chica, y la que sigue a un `$…$` salía en LM Math.
  // La ambiente se lee ANTES de tocar nada, y por dos razones: setRelFontSize la
  // invalida (la pone en FN_NOFACE para forzar la re-emisión de tamaño), y el
  // setFontFace de abajo la sobrescribiría con la cara de ESTE trozo.
  const FontFace ambient = g.getFontFace();

  // Cadena de resolución de "hereda la cara ambiente" (§7.3), de lo más local a lo
  // más global: la cara horneada en el trozo → la ambiente de la LÍNEA (la que
  // guardó TextLine::draw, que no es la vigente si un trozo anterior era `$…$`) → la
  // ambiente del DOCUMENTO (la que fijó `font`) → Times-Roman si nadie fijó ninguna.
  // Los dos últimos eslabones son nuevos: sin ellos un trozo FN_NOFACE fuera de una
  // TextLine —un rótulo de eje sin marcado, que parse_text devuelve como Text pelón—
  // se saltaba setFontFace y salía con la fuente que hubiera dejado el texto anterior.
  FontFace face = textstate.font_face;
  if (face == FN_NOFACE) face = g.getInheritedFace();
  if (face == FN_NOFACE) face = ambient;
  if (face == FN_NOFACE) face = FN_TIMES_ROMAN;
  g.setRelFontSize(textstate.font_size);
  g.setFontFace(face);
  // valign para texto SIMPLE (parse_text devuelve un Text pelón, sin TextLine):
  // desplaza la pluma una vez antes de emitir. En texto compuesto este Text se
  // dibuja desde TextLine::draw, que ya puso valign a 0 (aplica el desplazamiento
  // a la línea entera), así que aquí no se duplica. No se restaura: es estado
  // persistente y cada text() se reposiciona con un moveto absoluto propio.
  if (g.getTextValign() > 0)
    g.rmoveto(0, g.valignShift());
  g.text(text);
  // La cara de este trozo NO sobrevive al trozo: se devuelve la ambiente al estado
  // lógico. Va DESPUÉS de g.text() porque SVGDisplay::text lee dspstate.fontFace para
  // decidir familia, estilo y tabla de codepoints del run (no tiene dev_face como
  // EPS/PDF). Ver Display::restoreAmbientFace.
  g.restoreAmbientFace(ambient);
}

void TextLine::draw(Display &g) {
  double vdesp;

  int text_align = g.getTextAlign();
  int text_valign = g.getTextValign();
  if (text_align > 0 || text_valign > 0) {
    // dx solo cuando hay alineación horizontal: con align=0 (left) el factor
    // width*fs/(3-align) NO es cero (=width*fs/3), colaría un corrimiento espurio
    // si valign viene solo. dy (valign) sale del helper centralizado del Display.
    double dx = (text_align > 0) ? width() * g.getFontSize() / (3 - text_align) : 0.0;
    g.rmoveto(-dx, g.valignShift());
    g.setTextAlign(0);
    g.setTextValign(0);   // se puso a 0 para que los Text hijos no re-apliquen valign
  }
  // Cara AMBIENTE de la línea, capturada antes de dibujar ningún trozo: para cuando
  // un trozo se dibuja, la cara vigente ya puede ser la que puso un trozo ANTERIOR
  // (un run de `$…$` deja el dispositivo en LM Math), que no es la ambiente. Un
  // trozo con FN_NOFACE ("hereda la ambiente") la resuelve contra esto (Text::draw).
  //
  // Sin ella, FN_NOFACE estaba implementado como NO TOCAR el dispositivo, que solo
  // equivale a "la ambiente" mientras nadie la haya tocado. Dentro de una línea sí
  // la tocan, y se veía en cualquier rótulo de eje o entrada de leyenda que mezcle
  // fórmula y prosa: la prosa tras `$…$` salía en la fuente del math, y la prosa
  // tras un sub/superíndice salía al tamaño reducido del índice (ver Text::draw:
  // saltarse setFontFace también se salta el refresco de TAMAÑO). Un `text()` normal
  // nunca lo sufrió porque hornea FN_DEFAULT en todos sus trozos.
  // Si nadie fijó cara en el documento (lo normal en una figura que nunca escribe
  // `font`), la ambiente ES la cara por default — el mismo criterio que ya aplican
  // los guards de EPSDisplay::text/PDFDisplay::text al primer texto del documento, y
  // el que usa change_font_face para los modificadores de bit sobre FN_NOFACE.
  // Resolverla aquí es lo que hace que el arreglo sirva en una figura sin `font`,
  // que es justo donde vive el bug (los rótulos de axis/legend nacen con FN_NOFACE).
  { FontFace amb = g.getFontFace();
    g.setInheritedFace(amb != FN_NOFACE ? amb : FN_TIMES_ROMAN); }
  for (const auto &item : textline) {
    // Item inline no-Text (Fraction, \frac inline): se compone a sí mismo en la pluma
    // actual y la avanza por su ancho. Su ÚNICA mecánica de run es la entradilla math
    // (pre_space, tamaño pleno → sin factor de script); la composición 2-D la resuelve
    // Fraction::draw. En el corpus sin \frac esta rama no se toca → el refactor a
    // contenedor genérico es byte-idéntico (plan_frac.md, Paso 1).
    if (item->getType() == GI_FRACTION) {
      double ps = static_cast<Fraction *>(item.get())->preSpace();
      if (ps != 0)
        g.rmoveto(ps * g.getFontSize(), 0);
      item->draw(g);
      continue;
    }
    if (item->getType() == GI_ACCENT) {         // \hat/\vec: como Fraction, un hijo
      double ps = static_cast<Accent *>(item.get())->preSpace();
      if (ps != 0)
        g.rmoveto(ps * g.getFontSize(), 0);
      item->draw(g);
      continue;
    }
    if (item->getType() != GI_TEXT) {   // otros tipos futuros: se dibujan tal cual
      item->draw(g);
      continue;
    }
    Text *text = static_cast<Text *>(item.get());
    TextState ts = text->getState();
    //printf("text <%s> state %s\n", text->getText().c_str(), ts.str().c_str());
    // Espaciado math del run (plan_text_space, Parte B): rmoveto horizontal antes de
    // dibujar. En unidades de dispositivo (pre_space em · relsize · tamaño de fuente),
    // igual que el desplazamiento vertical de sub/superíndices de abajo — no transforma.
    if (ts.pre_space != 0)
      g.rmoveto(ts.pre_space * ts.font_size * g.getFontSize(), 0);
    if (ts.script != 0) {
      vdesp = (ts.script < 0) ? -g.getFontSize() * 0.14 : g.getFontSize() * 0.56;
      g.rmoveto(0, vdesp);
    }
    text->draw(g);
    if (ts.script != 0) {
      g.rmoveto(0, -vdesp);
    }
  }
  g.setInheritedFace(FN_NOFACE);    // fuera de la línea no hay ambiente que heredar
  if (text_align > 0)
    g.setTextAlign(text_align);
  if (text_valign > 0)
    g.setTextValign(text_valign);   // estado persistente: vale para los text() siguientes
}

void TextBlock::draw(Display &g) {
  if (lines.empty()) return;

  // El ancla del bloque: la pluma tal como la dejó el GS_PLUMEPOSITION previo. Se
  // relee para CADA renglón porque TextLine::draw mueve la pluma (corrimiento de
  // alineación + avance del texto), así que no se puede encadenar con movimientos
  // relativos en x.
  point anchor;
  g.getPlumePosition(anchor);

  // El interlineado sale del tamaño de fuente VIGENTE, que es la razón de que esto
  // viva en el motor: en parse-time no se conoce. rmoveto no transforma (va en
  // unidades de dispositivo), igual que el desplazamiento de sub/superíndices de
  // TextLine::draw, así que `lead` se usa tal cual.
  const double lead = leading * g.getFontSize();
  const std::size_t n = lines.size();

  // valign se aplica AL BLOQUE, no a cada renglón: `middle` centra el conjunto. La
  // alineación fina dentro de cada renglón la sigue haciendo Text/TextLine con el
  // valign vigente, que no se toca. Con un solo renglón y0 = 0 → comportamiento
  // idéntico al de antes (cero churn en todo el corpus).
  double y0 = 0;
  switch (g.getTextValign()) {
    case 2: y0 = lead * (double)(n - 1) / 2.0; break;   // middle
    case 3: y0 = lead * (double)(n - 1);       break;   // bottom
    default: break;                                     // baseline / top: 1ª línea en el ancla
  }

  for (std::size_t i = 0; i < n; i++) {
    if (!lines[i]) continue;                            // renglón vacío: solo consume interlineado
    // Cada renglón arranca del MISMO estado, acotado con push/pop. Sin esto, un
    // renglón que cambia la cara —el caso corriente: `"$\Delta T_1$/n(BT 10.3…)"`,
    // donde el primero es math— la deja puesta en el dispositivo, y el siguiente,
    // que hereda la ambiente (FN_NOFACE), sale con la fuente del anterior. Es la
    // misma familia de errores que FN_NOFACE, ahora ENTRE renglones: "heredar la
    // ambiente" tiene que significar la del bloque, no la del vecino de arriba.
    g.pushDrawState();
    g.moveto_nopath(anchor.x, anchor.y);
    g.rmoveto(0, y0 - lead * (double)i);
    lines[i]->draw(g);
    g.popDrawState();
  }
}

// Ancho em de un item de línea. Sin RTTI (-fno-rtti): despacho por getType() + cast.
// Text mide con su TextState (incluye la entradilla pre_space, Parte B); un Fraction
// reporta el suyo. La misma tabla la usan width() y draw() para no divergir.
double TextLine::itemWidth(GraphicsItem *g) {
  if (g->getType() == GI_TEXT) {
    Text *t = static_cast<Text *>(g);
    TextState ts = t->getState();
    return ts.pre_space * ts.font_size + text_width(ts, t->getText());
  }
  if (g->getType() == GI_FRACTION) {
    Fraction *f = static_cast<Fraction *>(g);
    return f->preSpace() + f->width();     // entradilla math + ancho de la fracción
  }
  if (g->getType() == GI_ACCENT) {
    Accent *ac = static_cast<Accent *>(g);
    return ac->preSpace() + ac->width();
  }
  return 0;   // otros tipos: fuera del modelo de línea
}

double TextLine::width() {
  double w = 0;
  for (const auto &item : textline)
    w += itemWidth(item.get());
  return w;
}

// Composición \frac ---------------------------------------------------------
// Métricas verticales de la fracción (em, relativas al tamaño base). El eje = la altura
// de la raya; la holgura = el hueco que se deja entre la raya y el contenido. Los
// corrimientos de sub/superíndice son los MISMOS que aplica TextLine::draw (0.56 arriba,
// 0.14 abajo): así medir y dibujar concuerdan. No hay métricas verticales POR GLIFO (los
// mapas solo dan ancho), así que la altura de mayúscula y la profundidad de descendente
// son aproximadas — el numerador con subíndices y el denominador con superíndices ya no
// chocan con la raya, a costa de una holgura un pelo generosa en glifos sin ascendente
// o descendente plenos (plan_frac.md punto 3).
static constexpr double kFracAxis    = 0.30;   // altura de la raya sobre la línea base (em)
static constexpr double kFracGap     = 0.06;   // holgura raya ↔ contenido (em)
static constexpr double kFracScript  = 1.0;    // num/den a tamaño pleno (display style, como la referencia)
static constexpr double kGlyphAscent = 0.70;   // altura de mayúscula aprox. (em)
static constexpr double kGlyphDescent= 0.18;   // profundidad de descendente aprox. (em)
static constexpr double kSupShift    = 0.56;   // corrimiento de superíndice (= TextLine::draw)
static constexpr double kSubShift    = 0.14;   // corrimiento de subíndice   (= TextLine::draw)

// Extensión vertical de UN run según su estado: tope y fondo (em) respecto de la línea
// base del renglón, contando el corrimiento del script y el tamaño reducido del glifo.
static void runVExtent(const TextState &ts, double &top, double &bot) {
  double shift = (ts.script > 0) ? kSupShift : (ts.script < 0) ? -kSubShift : 0.0;
  top = shift + kGlyphAscent  * ts.font_size;
  bot = shift - kGlyphDescent * ts.font_size;
}

// Extensión vertical de un hijo (Text/TextLine/Fraction). Mutuamente recursiva con
// Fraction::vExtent para fracciones anidadas. Sin RTTI: despacho por getType().
static void childVExtent(GraphicsItem *g, double &ascent, double &descent) {
  ascent = 0; descent = 0;
  if (!g) return;
  if (g->getType() == GI_TEXT) {
    double top, bot; runVExtent(static_cast<Text *>(g)->getState(), top, bot);
    ascent = top; descent = -bot;
  } else if (g->getType() == GI_TEXTLINE) {
    static_cast<TextLine *>(g)->vExtent(ascent, descent);
  } else if (g->getType() == GI_FRACTION) {
    static_cast<Fraction *>(g)->vExtent(ascent, descent);
  } else if (g->getType() == GI_ACCENT) {
    static_cast<Accent *>(g)->vExtent(ascent, descent);
  }
}

void TextLine::vExtent(double &ascent, double &descent) {
  ascent = 0; descent = 0;
  for (const auto &item : textline) {
    double a = 0, d = 0;
    childVExtent(item.get(), a, d);
    if (a > ascent) ascent = a;
    if (d > descent) descent = d;
  }
}

// vExtent de la fracción: num/den se dibujan a kFracScript del tamaño (scriptstyle), así
// que sus extents em escalan por ese factor; el eje y la holgura van al tamaño base (la
// raya se sitúa en el eje del texto que rodea la fracción). Permite anidar.
void Fraction::vExtent(double &ascent, double &descent) {
  double numAsc, numDesc, denAsc, denDesc;
  childVExtent(num.get(), numAsc, numDesc);
  childVExtent(den.get(), denAsc, denDesc);
  double numBase = kFracAxis + kFracGap + kFracScript * numDesc;   // base del numerador (em)
  double denBase = kFracAxis - kFracGap - kFracScript * denAsc;    // base del denominador (em)
  ascent  = numBase + kFracScript * numAsc;        // tope del numerador
  descent = -(denBase - kFracScript * denDesc);    // fondo del denominador
}

// Ancho em de un hijo. Sin RTTI (-fno-rtti): se decide por getType() + cast.
double Fraction::childWidth(GraphicsItem *g) {
  if (!g) return 0;
  if (g->getType() == GI_TEXTLINE) return static_cast<TextLine *>(g)->width();
  if (g->getType() == GI_TEXT) {
    Text *t = static_cast<Text *>(g);
    return text_width(t->getState(), t->getText());
  }
  return 0;   // TextBlock u otros: fuera del spike
}

// Ancho em de la fracción = el del hijo más ancho, EN scriptstyle (num/den se dibujan a
// kFracScript del tamaño, así que su ancho real es ese factor del hijo más ancho).
double Fraction::width() {
  double wn = childWidth(num.get());
  double wd = childWidth(den.get());
  return kFracScript * ((wn > wd) ? wn : wd);
}

// La fracción se compone INLINE: arranca en la pluma actual (que TextLine ya colocó,
// incluida la alineación del renglón y el pre_space) y la deja AVANZADA por su ancho W,
// lista para el siguiente elemento. Toda la geometría es device-relativa con movimientos
// de NETO CERO alrededor de cada parte: no se apoya en gsave/grestore para restaurar la
// pluma, porque el SVG no la salva en push/popDrawState (a diferencia del currentpoint
// nativo de PS/PDF). La alineación y el valign los maneja TextLine::draw ANTES de llegar
// aquí (pone align/valign a 0 para los hijos), así que la fracción no los toca.
void Fraction::draw(Display &g) {
  double baseFs = g.getFontSize();
  double fs = baseFs * kFracScript;         // num/den en scriptstyle (más chicos que el texto)
  double wn = childWidth(num.get()) * fs;   // a puntos de dispositivo, ya al tamaño reducido
  double wd = childWidth(den.get()) * fs;
  double W  = (wn > wd) ? wn : wd;
  double dxn = (W - wn) / 2.0;              // centra el más angosto sobre W
  double dxd = (W - wd) / 2.0;

  // Colocación por EXTENSIÓN VERTICAL MEDIDA (plan_frac.md punto 3): se mide cuánto baja
  // el numerador de su línea base (numDesc, incluye subíndices) y cuánto sube el
  // denominador (denAsc, incluye superíndices) y se coloca cada uno para que su borde
  // hacia la raya la libre por `kFracGap`. Los extents se miden en em y se llevan a
  // dispositivo con `fs` (el tamaño reducido al que se dibujan); la raya y la holgura van
  // al tamaño BASE (la raya se sitúa en el eje del texto que rodea la fracción). Reducir
  // el tamaño del dispositivo —y no cada run— hace que el corrimiento de super/subíndice
  // (0.56/0.14·getFontSize() en TextLine::draw) escale solo, y que un \frac anidado caiga
  // en scriptscript sin código extra.
  double numAsc, numDesc, denAsc, denDesc;
  childVExtent(num.get(), numAsc, numDesc);
  childVExtent(den.get(), denAsc, denDesc);
  double axis    = kFracAxis * baseFs;                       // altura de la raya (tamaño base)
  double numBase = (kFracAxis + kFracGap) * baseFs + numDesc * fs;   // base del numerador
  double denBase = (kFracAxis - kFracGap) * baseFs - denAsc * fs;    // base del denominador

  g.setFontSize(fs);   // num/den se dibujan reducidos; se restaura antes de la raya

  // Numerador: sube y centra, dibuja (la pluma avanza wn), y REGRESA con neto cero.
  g.rmoveto(dxn, numBase);
  if (num) num->draw(g);
  g.rmoveto(-(dxn + wn), -numBase);

  // Denominador: baja y centra, dibuja (avanza wd), y regresa.
  g.rmoveto(dxd, denBase);
  if (den) den->draw(g);
  g.rmoveto(-(dxd + wd), -denBase);

  g.setFontSize(baseFs);   // raya y avance al tamaño base

  // Raya al ancho W, a la altura del eje. Primitiva dedicada (no altera la pluma).
  g.fracRule(axis, W, baseFs * 0.045);

  // Átomo inline: deja la pluma avanzada por W para el siguiente elemento del renglón.
  g.rmoveto(W, 0);
}

// Composición \hat / \vec ---------------------------------------------------
// La marca se DIBUJA (ver el comentario de la clase). Su tamaño se toma del ancho de
// la base y no de una constante: sobre una letra ancha sale ancha, que es lo que en
// TeX exige pedir \widehat aparte.
static constexpr double kGlyphXHeight = 0.46;   // altura de la x aprox. (em)
static constexpr double kAccGap    = 0.10;   // holgura base ↔ marca (em)
static constexpr double kAccHeight = 0.14;   // alto del pico del circunflejo (em)
static constexpr double kAccWidth  = 0.85;   // ancho de la marca, en fracción de la base
static constexpr double kAccHead   = 0.28;   // largo de las barbas de \vec, en fracción del ancho

double Accent::width() { return Fraction::childWidth(base.get()); }

// Altura (em) a la que empieza la marca. Sale del extent MEDIDO de la base, con una
// corrección: `childVExtent` usa kGlyphAscent, que es altura de MAYÚSCULA, porque no
// hay métricas verticales por glifo (los mapas de la fuente solo dan ancho). Sobre una
// minúscula sin ascendente —justo el caso de la física: n^, r^, v^— eso deja la marca
// flotando un cuarto de em de más.
//
// La corrección es una heurística ACOTADA a propósito: solo cuando la base es UNA letra
// suelta, sin script, y de las que no suben. Cualquier otra cosa (una mayúscula, una
// palabra, algo con subíndice, una fórmula) conserva el extent completo, que nunca queda
// corto. Es del mismo tipo que las tablas de acentos de TeX, sin serlo.
static double accentBaseTop(GraphicsItem *g) {
  double asc, desc;
  childVExtent(g, asc, desc);
  // Desenvuelve un TextLine de un solo hijo: parse_sub devuelve eso para `\hat{n}`.
  if (g && g->getType() == GI_TEXTLINE) {
    TextLine *tl = static_cast<TextLine *>(g);
    g = (tl->length() == 1) ? tl->itemAt(0) : nullptr;
  }
  if (!g || g->getType() != GI_TEXT) return asc;
  Text *t = static_cast<Text *>(g);
  const std::string &str = t->getText();
  if (str.size() != 1 || t->getState().script != 0) return asc;
  static const std::string kSinAscendente = "acemnorsuvwxz";
  if (kSinAscendente.find(str[0]) == std::string::npos) return asc;
  return kGlyphXHeight * t->getState().font_size;
}

// El acento no cambia el ancho ni el descenso: solo sube el techo, que es lo que
// necesita un \frac o un renglón que lo contenga para no encimarse.
void Accent::vExtent(double &ascent, double &descent) {
  childVExtent(base.get(), ascent, descent);
  double top = accentBaseTop(base.get()) + kAccGap + kAccHeight;
  if (top > ascent) ascent = top;            // la misma altura que usa draw()
}

void Accent::draw(Display &g) {
  double fs = g.getFontSize();
  double wb = Fraction::childWidth(base.get()) * fs;

  // La base se dibuja tal cual y avanza la pluma; se vuelve con neto cero, igual que
  // hace Fraction con cada uno de sus dos hijos.
  if (base) base->draw(g);
  g.rmoveto(-wb, 0);

  double y  = accentBaseTop(base.get()) * fs + kAccGap * fs;   // encima del techo de la base
  double wm = kAccWidth * wb;                // la marca sigue el ancho de la base
  double x0 = (wb - wm) / 2.0;               // centrada sobre ella
  double lw = fs * 0.045;                    // el mismo grosor que la raya de \frac

  if (kind == HAT) {
    g.penSegment(x0, y, x0 + wm/2, y + kAccHeight*fs, lw);
    g.penSegment(x0 + wm/2, y + kAccHeight*fs, x0 + wm, y, lw);
  } else {                                   // VEC: asta y dos barbas en la punta
    double hy = kAccHeight * fs * 0.55;
    g.penSegment(x0, y, x0 + wm, y, lw);
    g.penSegment(x0 + wm, y, x0 + wm - kAccHead*wm, y + hy, lw);
    g.penSegment(x0 + wm, y, x0 + wm - kAccHead*wm, y - hy, lw);
  }

  g.rmoveto(wb, 0);                          // átomo inline: la pluma queda avanzada
}
